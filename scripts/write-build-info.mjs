import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));

const WORKSPACE_PACKAGE_FILES = [
  'package.json',
  'apps/server/package.json',
  'apps/web/package.json',
  'packages/shared/package.json',
];

function parseSemver(version) {
  if (typeof version !== 'string') return null;
  const match = /^v?(\d+)\.(\d+)\.(\d+)$/.exec(version.trim());
  if (!match) return null;
  return {
    normalized: `${Number(match[1])}.${Number(match[2])}.${Number(match[3])}`,
    parts: [Number(match[1]), Number(match[2]), Number(match[3])],
  };
}

function compareSemver(a, b) {
  for (let i = 0; i < 3; i += 1) {
    if (a.parts[i] !== b.parts[i]) return a.parts[i] - b.parts[i];
  }
  return 0;
}

/**
 * Keeps root/workspace package.json versions and `AGENTOPSDECK_VERSION` in
 * `packages/shared/src/protocol.ts` automatically synchronized with the highest
 * configured semver across workspace manifests, `protocol.ts`, and `HEAD` tags.
 * Only writes files whose version string actually differs.
 */
export function syncWorkspaceVersion(targetRoot = root) {
  const rootPkgPath = join(targetRoot, 'package.json');
  const protocolPath = join(targetRoot, 'packages/shared/src/protocol.ts');
  if (!existsSync(rootPkgPath) || !existsSync(protocolPath)) return null;

  const candidates = [];
  for (const rel of WORKSPACE_PACKAGE_FILES) {
    const file = join(targetRoot, rel);
    if (!existsSync(file)) continue;
    try {
      const parsed = parseSemver(JSON.parse(readFileSync(file, 'utf8')).version);
      if (parsed) candidates.push(parsed);
    } catch { /* ignore malformed fixture manifest */ }
  }
  try {
    const protoText = readFileSync(protocolPath, 'utf8');
    const match = /export const AGENTOPSDECK_VERSION\s*=\s*'([^']+)'/.exec(protoText);
    const parsed = match ? parseSemver(match[1]) : null;
    if (parsed) candidates.push(parsed);
  } catch { /* ignore */ }
  try {
    const top = execFileSync('git', ['rev-parse', '--show-toplevel'], {
      cwd: targetRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
    if (realpathSync(top) === realpathSync(targetRoot)) {
      const tags = execFileSync('git', ['tag', '--points-at', 'HEAD'], {
        cwd: targetRoot,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      })
        .split(/\r?\n/)
        .map((line) => parseSemver(line))
        .filter(Boolean);
      candidates.push(...tags);
    }
  } catch { /* ignore non-git archives */ }

  if (candidates.length === 0) return null;
  candidates.sort(compareSemver);
  const targetVersion = candidates[candidates.length - 1].normalized;

  for (const rel of WORKSPACE_PACKAGE_FILES) {
    const file = join(targetRoot, rel);
    if (!existsSync(file)) continue;
    const raw = readFileSync(file, 'utf8');
    const updated = raw.replace(/("version"\s*:\s*")([^"]+)(")/, `$1${targetVersion}$3`);
    if (updated !== raw) writeFileSync(file, updated);
  }

  const protoRaw = readFileSync(protocolPath, 'utf8');
  const protoUpdated = protoRaw.replace(
    /(export const AGENTOPSDECK_VERSION\s*=\s*')([^']+)(')/,
    `$1${targetVersion}$3`,
  );
  if (protoUpdated !== protoRaw) writeFileSync(protocolPath, protoUpdated);

  return targetVersion;
}

// Beijing calendar date + two-hour bucket (0–11); independent of the host TZ.
export function formatBuildNumber(date) {
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Shanghai', year: '2-digit', month: '2-digit', day: '2-digit',
    hour: '2-digit', hourCycle: 'h23',
  }).formatToParts(date).map(part => [part.type, part.value]));
  return `${parts.year}.${parts.month}${parts.day}${Math.floor(Number(parts.hour) / 2)}`;
}

export function writeBuildInfo() {
  let revision = 'unknown', dirty = false;
  try {
    const top = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    if (realpathSync(top) !== realpathSync(root)) throw new Error('Source archive inside an unrelated repository');
    revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    dirty = !!execFileSync('git', ['status', '--porcelain', '--untracked-files=normal'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch { /* Source archives without Git honestly advertise unknown provenance. */ }
  const builtAt = new Date();
  writeFileSync(new URL('../packages/shared/src/build-info.generated.ts', import.meta.url),
    `// Generated by scripts/write-build-info.mjs; do not edit.\nexport const AGENTOPSDECK_BUILD = ${JSON.stringify({ revision, dirty, buildNumber: formatBuildNumber(builtAt), builtAt: builtAt.toISOString() })} as const;\n`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) writeBuildInfo();
