// Run with the server's tsx loader. Executes the pinned Python contract POC after SHA-256
// and stdlib-only AST admission, then feeds frames made by the verified functions into our codec.
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { lstatSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { HermesFrameDecoder, parseHermesEvent, readyEpoch, terminalStatus } from '../apps/server/src/hermes/protocol.ts';
import { planHermesReplay } from '../apps/server/src/hermes/replay.ts';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REQUIRED_FILES = ['tui_gateway/event_replay.py', 'tui_gateway/server.py', 'tui_gateway/entry.py'];
const SHA256_RE = /^[0-9a-f]{64}$/i;

function parseCli(argv) {
  let expectedSpec = process.env.AOD_HERMES_EXPECTED_SHA256 ?? '';
  const positional = [];
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--expected-sha256') {
      expectedSpec = argv[index + 1] ?? '';
      index += 1;
    } else if (arg.startsWith('--expected-sha256=')) {
      expectedSpec = arg.slice('--expected-sha256='.length);
    } else {
      positional.push(arg);
    }
  }
  if (!positional[0] || !expectedSpec) {
    throw new Error(
      'Usage: verify-hermes-wire.mjs <pinned-hermes-source> --expected-sha256 <json-or-manifest> [python-executable]',
    );
  }
  const rawText = expectedSpec.trim();
  let parsed;
  if (rawText.startsWith('{')) {
    parsed = JSON.parse(rawText);
  } else {
    const manifestPath = resolve(rawText);
    const st = lstatSync(manifestPath);
    if (!st.isFile() || st.isSymbolicLink()) {
      throw new Error('Expected SHA-256 manifest must be a regular non-symlink file');
    }
    parsed = JSON.parse(readFileSync(manifestPath, 'utf8'));
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('Expected SHA-256 manifest must be a JSON object');
  }
  const keys = Object.keys(parsed);
  if (keys.length !== REQUIRED_FILES.length || REQUIRED_FILES.some(key => !Object.hasOwn(parsed, key))) {
    throw new Error(`Expected SHA-256 manifest must contain exact keys: ${REQUIRED_FILES.join(', ')}`);
  }
  const normalized = {};
  for (const key of REQUIRED_FILES) {
    const value = parsed[key];
    if (typeof value !== 'string' || !SHA256_RE.test(value)) {
      throw new Error(`Invalid SHA-256 digest for ${key}`);
    }
    normalized[key] = value.toLowerCase();
  }
  return {
    sourceRoot: resolve(positional[0]),
    pythonExecutable: positional[1] ?? 'python3',
    expectedJson: JSON.stringify(normalized),
  };
}

const cli = parseCli(process.argv.slice(2));
const result = spawnSync(cli.pythonExecutable, [
  '-B',
  resolve(repository, 'scripts/verify-hermes-contract.py'),
  cli.sourceRoot,
  '--expected-sha256',
  cli.expectedJson,
  '--wire',
], {
  cwd: repository, env: { PATH: process.env.PATH ?? '/usr/bin:/bin', ...(process.env.SystemRoot ? { SystemRoot: process.env.SystemRoot } : {}) },
  encoding: 'buffer', timeout: 10_000, maxBuffer: 1024 * 1024,
});
if (result.status !== 0 || result.error) throw new Error('Upstream isolated contract POC failed');
const decoder = new HermesFrameDecoder();
const events = [];
// Exercise byte-split Chinese text generated by upstream, not just a copied fixture.
for (const byte of result.stdout) {
  for (const frame of decoder.push(Uint8Array.of(byte))) {
    assert.equal(frame.kind, 'notification');
    assert.equal(frame.method, 'event');
    events.push(parseHermesEvent(frame.params));
  }
}
decoder.finish();
assert.equal(events.length, 4);
const epoch = readyEpoch(events[0]);
assert.ok(epoch);
assert.equal(events[2].payload.text, '你好');
assert.equal(terminalStatus(events[3]), 'completed');
const replay = planHermesReplay({ epoch, sessionId: 'poc-session', seq: 0 }, {
  epoch, latest_seq: 3, truncated: false, count: 3,
  events: events.slice(1).map(event => ({ type: event.type, session_id: event.sessionId, seq: event.seq, payload: event.payload })),
});
assert.equal(replay.kind, 'apply');
assert.equal(replay.next.seq, 3);
console.log(JSON.stringify({ kind: 'upstream-frames-through-agentopsdeck-source', frames: events.length,
  utf8: true, ready: true, terminal: true, replay: true, backendStarted: false }));
