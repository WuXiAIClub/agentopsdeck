import assert from 'node:assert/strict';
import test from 'node:test';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Hono } from 'hono';
import { HubStore } from '../hub/hub-store.js';
import type { HubPrincipal } from '../hub/identity.js';
import { registerHubRoleAccessRoutes } from './hub-role-access.js';
import { registerHubNodeGrantRoutes } from './hub-node-grants.js';
import { registerHubOwnedSessionSharingRoutes } from './hub-owned-session-sharing.js';
import { encodeHubSessionId } from '../hub/session-id.js';

test('role HTTP routes enforce CAS, delegation, strict provider schema and managed-root protection', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'agentopsdeck-role-http-'));
  const store = new HubStore(join(directory, 'hub.sqlite'), 'synthetic-vault');
  try {
    const owner = store.createUser('Owner'), manager = store.createUser('Manager'), member = store.createUser('Member');
    store.upsertConnection({ id: 'node', ownerUserId: owner.id, kind: 'remote', label: 'Test', connectorUrl: 'http://unused.invalid' });
    store.pinConnectionNode('node', owner.id, store.connectionAuthority('node', owner.id)!, `node_${randomUUID()}`);
    let actor: HubPrincipal = { userId: 'default', admin: true };
    const app = new Hono(), deps = { hubStore: store, principal: () => actor };
    registerHubRoleAccessRoutes(app, deps);
    registerHubNodeGrantRoutes(app, deps);
    registerHubOwnedSessionSharingRoutes(app, deps);
    const base = `/api/hub/v1/access/${owner.id}/connections/node/members/`;
    const request = (path: string, method = 'GET', body?: unknown) => app.request(path, { method, ...(body ? { body: JSON.stringify(body) } : {}) });
    const target = (userId: string) => ({ ownerUserId: owner.id, connectionId: 'node', userId });
    const input = (role = 'developer') => ({ role, version: 0, nodeVersion: store.connectionAuthority('node', owner.id)!, migrateLegacy: true,
      environments: { codex: 'developer', openclaw: role === 'admin' ? 'observer' : 'disabled' } });
    assert.equal((await request(base + manager.id, 'PUT', input('admin'))).status, 200);
    actor = { userId: manager.id, admin: false };
    const listing = await (await request('/api/hub/v1/access/directory')).json();
    assert.equal(listing.connections.length, 1);
    assert.equal(listing.connections[0].appointAdministrators, false);
    assert.equal(JSON.stringify(listing).includes('unused.invalid'), false);
    assert.equal((await request(base + member.id, 'PUT', input('admin'))).status, 409);
    assert.equal(store.roles.membership(target(member.id)).version, 0);
    assert.equal((await request(base + member.id, 'PUT', { ...input(), environments: { ...input().environments, hermes: 'developer' } })).status, 400);
    assert.equal((await request(base + member.id, 'PUT', input())).status, 200);
    const root = store.grants.received(member.id).grants[0]!;
    assert.equal((await request(base + member.id, 'PUT', input())).status, 409);
    assert.equal(store.grants.received(member.id).grants.length, 1);
    assert.equal((await request(base + manager.id, 'PUT', { ...input(), version: 1 })).status, 409);
    assert.equal((await request(`/api/hub/v1/access/users/${member.id}/hub-role`, 'PUT', { role: 'admin', version: 0 })).status, 403);
    actor = { userId: member.id, admin: false };
    assert.equal((await request(base + member.id)).status, 403);
    actor = { userId: owner.id, admin: false };
    const grantPath = `/api/hub/v1/connections/node/grants/${root.id}`;
    assert.equal((await request(grantPath, 'DELETE', { version: root.version })).status, 409);
    assert.equal((await request(grantPath, 'PUT', { version: root.version, nodeVersion: root.nodeVersion, policy: { runtime: 'codex', actions: ['messages:read'] } })).status, 409);
    assert.equal((await request('/api/hub/v1/connections/node/grants', 'POST', { userId: member.id, nodeVersion: root.nodeVersion, policy: { runtime: 'codex', actions: ['messages:read'] } })).status, 409);
    assert.equal(store.grants.received(member.id).grants.length, 1);
    actor = { userId: 'default', admin: true };
    assert.equal((await request(`/api/hub/v1/access/users/${member.id}/hub-role`, 'PUT', { role: 'admin', version: 0 })).status, 200);
    assert.equal((await request(`/api/hub/v1/access/users/${member.id}/hub-role`, 'PUT', { role: 'member', version: 0 })).status, 409);
    assert.equal((await request(`/api/hub/v1/access/users/${member.id}/hub-role`, 'PUT', { role: 'member', version: 1 })).status, 200);
    const sharingPath = `/api/hub/v1/sessions/${encodeURIComponent(encodeHubSessionId('node', 'codex:legacy-owned'))}/collaborators`;
    assert.equal((await request(sharingPath)).status, 404);
    actor = { userId: manager.id, admin: false };
    assert.equal((await request(sharingPath)).status, 404);
    actor = { userId: owner.id, admin: false };
    assert.equal((await request(sharingPath)).status, 200);
    const shared = await request(sharingPath, 'POST', { userId: member.id, role: 'collaborator', media: true });
    assert.equal(shared.status, 201);
    const { grant } = await shared.json();
    assert.ok(store.grants.authorize(target(member.id), 'messages:send', { runtime: 'codex', sessionKey: 'codex:legacy-owned' }));
    assert.equal((await request(sharingPath, 'POST', { userId: member.id, role: 'collaborator' })).status, 409);
    assert.equal((await request(`${sharingPath}/${root.id}`, 'DELETE', { version: root.version })).status, 409);
    assert.equal((await request(`${sharingPath}/${grant.id}`, 'PUT', { version: 1, role: 'observer', live: false, queue: false, media: false })).status, 200);
    assert.equal(store.grants.authorize(target(member.id), 'messages:send', { runtime: 'codex', sessionKey: 'codex:legacy-owned' }), undefined);
    assert.equal((await request(`${sharingPath}/${grant.id}`, 'PUT', { version: 1, role: 'collaborator' })).status, 409);
    actor = { userId: 'default', admin: true };
    assert.equal((await request(base + member.id, 'PUT', { ...input(), version: 1 })).status, 200);
    assert.ok(store.grants.authorize(target(member.id), 'messages:read', { runtime: 'codex', sessionKey: 'codex:legacy-owned' }));
    actor = { userId: owner.id, admin: false };
    assert.equal((await request(`${sharingPath}/${grant.id}`, 'DELETE', { version: 2 })).status, 200);
    assert.equal(store.grants.authorize(target(member.id), 'messages:read', { runtime: 'codex', sessionKey: 'codex:legacy-owned' }), undefined);
  } finally { store.close(); rmSync(directory, { recursive: true, force: true }); }
});
