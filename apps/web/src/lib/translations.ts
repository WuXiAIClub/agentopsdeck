export type TranslationKey = keyof typeof chinese;
export type Locale = 'en' | 'zh-CN';
export type TranslationParams = Record<string, string | number>;

export function resolveLocale(stored?: string | null, browserLanguage = 'en'): Locale {
  if (stored === 'en' || stored === 'zh-CN') return stored;
  return /^zh(?:-|$)/i.test(browserLanguage) ? 'zh-CN' : 'en';
}

/** Interpolation is plain text: React escapes values, including user labels. */
export function translateMessage(key: TranslationKey, locale: Locale, params?: TranslationParams): string {
  const template: string = locale === 'zh-CN' ? chinese[key] : key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => params && Object.hasOwn(params, name) ? String(params[name]) : match);
}
